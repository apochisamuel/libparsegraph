#include "harness.h"

/*
 * libparsegraph fuzz target.
 *
 * Input format: raw bytes interpreted as a sequence of 3-byte-header
 * protocol frames: [opcode:1][length:2 LE][payload:N]
 *
 * Opcodes (0x01–0x0D):
 *   0x01  ADD_NODE       label(1), prop_count(1), [key(1)+val(8)]*
 *   0x02  ADD_EDGE       src(4), dst(4), type(1)
 *   0x03  DELETE_NODE    id(4)
 *   0x04  SET_PROPERTY   id(4), key(1), val(8)
 *   0x05  QUERY          binary query blob
 *   0x06  COMPACT        (no payload)
 *   0x07  SESSION_OPEN   sid(1)
 *   0x08  SESSION_CLOSE  sid(1)
 *   0x09  TXN_BEGIN      sid(1)
 *   0x0A  TXN_COMMIT     sid(1)
 *   0x0B  BATCH          sid(1), count(1), sub-ops...
 *   0x0C  SNAPSHOT       (no payload)
 *   0x0D  INDEX_REBUILD  (no payload)
 *
 * The fuzzer discovers sequences of mutations, queries, session
 * lifecycle events, and compaction that trigger memory-safety bugs
 * in the engine's shared mutable state.
 */

/*
 * Primary entry point for libFuzzer.
 * Creates a seeded graph with baseline topology, then feeds the
 * fuzzer-generated bytes through the frame protocol.
 */
int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {
    if (size < 3) return 0;

    pg_harness h;
    if (pg_harness_init(&h) != PG_OK) return 0;

    /* seed with a connected graph so the fuzzer can immediately
       exercise query, traversal, and mutation paths */
    pg_harness_seed(&h);

    /* feed all input as protocol frames */
    pg_harness_feed(&h, data, size);

    pg_harness_free(&h);
    return 0;
}

/*
 * Standalone driver for replaying crash inputs.
 *
 * Usage: ./harness_replay <input.bin>
 *
 * Reads the file, passes it through the same code path as the
 * fuzzer, so ASAN can report the bug with a full stack trace.
 */
#ifndef FUZZING_BUILD_MODE_UNSAFE_FOR_PRODUCTION

static int replay_file(const char *path) {
    FILE *f = fopen(path, "rb");
    if (!f) {
        fprintf(stderr, "Cannot open %s\n", path);
        return 1;
    }

    fseek(f, 0, SEEK_END);
    long fsize = ftell(f);
    fseek(f, 0, SEEK_SET);

    if (fsize <= 0 || fsize > 1024 * 1024) {
        fprintf(stderr, "File too large or empty: %ld bytes\n", fsize);
        fclose(f);
        return 1;
    }

    uint8_t *data = malloc((size_t)fsize);
    if (!data) {
        fprintf(stderr, "OOM allocating %ld bytes\n", fsize);
        fclose(f);
        return 1;
    }

    size_t read = fread(data, 1, (size_t)fsize, f);
    fclose(f);

    if (read != (size_t)fsize) {
        fprintf(stderr, "Short read: %zu / %ld\n", read, fsize);
        free(data);
        return 1;
    }

    fprintf(stderr, "[harness] Replaying %s (%zu bytes)\n", path, read);

    LLVMFuzzerTestOneInput(data, read);

    fprintf(stderr, "[harness] Replay complete\n");
    free(data);
    return 0;
}

int main(int argc, char **argv) {
    if (argc < 2) {
        fprintf(stderr, "Usage: %s <input.bin> [input2.bin ...]\n", argv[0]);
        return 1;
    }

    int failures = 0;
    for (int i = 1; i < argc; i++) {
        if (replay_file(argv[i]) != 0) failures++;
    }
    return failures > 0 ? 1 : 0;
}

#endif /* !FUZZING_BUILD_MODE_UNSAFE_FOR_PRODUCTION */
